import functools

@functools.cache
def quadratic_bezier(t, p1x, p1y, c1x, c1y, p2x, p2y):
    """
    Квадратичная кривая Безье
    
    Parameters:
    t - параметр от 0 до 1
    p1x, p1y - начальная точка
    c1x, c1y - контрольная точка
    p2x, p2y - конечная точка
    
    Returns:
    x, y - координаты точки на кривой при параметре t
    """
    # Формула квадратичной кривой Безье:
    # B(t) = (1-t)² * P1 + 2*(1-t)*t * C + t² * P2
    
    # Вычисляем x-координату
    x = ((1 - t) ** 2) * p1x + 2 * (1 - t) * t * c1x + (t ** 2) * p2x
    
    # Вычисляем y-координату
    y = ((1 - t) ** 2) * p1y + 2 * (1 - t) * t * c1y + (t ** 2) * p2y
    
    return x, y

@functools.cache
def cubic_bezier(t, c1x=0, c1y=-1, c2x=2, c2y=1, p1x=-1, p1y=-1, p2x=1, p2y=1):
    """
    Кубическая кривая Безье
    
    Parameters:
    t - параметр от 0 до 1
    p1x, p1y - начальная точка
    c1x, c1y - первая контрольная точка
    c2x, c2y - вторая контрольная точка
    p2x, p2y - конечная точка
    
    Returns:
    x, y - координаты точки на кривой при параметре t
    """
    # Формула кубической кривой Безье:
    # B(t) = (1-t)³ * P1 + 3*(1-t)²*t * C1 + 3*(1-t)*t² * C2 + t³ * P2
    
    # Вычисляем x-координату
    x = ((1 - t) ** 3) * p1x + 3 * ((1 - t) ** 2) * t * c1x + 3 * (1 - t) * (t ** 2) * c2x + (t ** 3) * p2x
    
    # Вычисляем y-координату
    y = ((1 - t) ** 3) * p1y + 3 * ((1 - t) ** 2) * t * c1y + 3 * (1 - t) * (t ** 2) * c2y + (t ** 3) * p2y
    
    return x, y